import { chromium } from 'playwright';
import fs from 'fs';
const browser = await chromium.launch();
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
await page.goto('http://localhost:8090/annonces/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(1000);
await page.evaluate(() => localStorage.removeItem('pk_wishlist'));
const button = page.locator('.pk-card-wishlist').first();
const postId = await button.getAttribute('data-post-id');
await button.click();
const active = await button.getAttribute('aria-pressed');
const savedAfterAdd = await page.evaluate(() => JSON.parse(localStorage.getItem('pk_wishlist') || '[]'));
await button.click();
const inactive = await button.getAttribute('aria-pressed');
const savedAfterRemove = await page.evaluate(() => JSON.parse(localStorage.getItem('pk_wishlist') || '[]'));
const detail = await browser.newPage();
await detail.goto('http://localhost:8090/annonce/casablanca/appartement-lumineux-3-pieces/', { waitUntil: 'domcontentloaded' });
await detail.waitForTimeout(1000);
const detailData = await detail.evaluate(() => ({ gallery: document.querySelectorAll('[class*="gallery" i], [class*="slider" i], .slick-slider, .es-gallery').length, images: document.images.length, favorites: document.querySelectorAll('.pk-card-wishlist').length }));
const result = { postId, add: { ariaPressed: active, savedAfterAdd }, remove: { ariaPressed: inactive, savedAfterRemove }, detail: detailData, consoleErrors: errors, status: active === 'true' && inactive === 'false' && savedAfterAdd.includes(postId) && savedAfterRemove.length === 0 && detailData.gallery > 0 && detailData.images > 0 && errors.length === 0 ? 'PASS' : 'FAIL' };
fs.writeFileSync('rapport-estatik-interactions-6.14.1.json', JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result, null, 2));
await browser.close();
if (result.status !== 'PASS') process.exit(1);
